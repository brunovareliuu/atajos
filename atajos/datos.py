_cache_ses = {}  # path -> incremental data (offset, tokens, title…)


def _texto_usuario(contenido):
    if isinstance(contenido, str):
        t = contenido
    elif isinstance(contenido, list):
        t = " ".join(c.get("text", "") for c in contenido if isinstance(c, dict) and c.get("type") == "text")
    else:
        return ""
    t = t.strip()
    if not t or t.startswith("<") or t.startswith("[Request interrupted") or t.startswith("Caveat:"):
        return ""
    return " ".join(t.split())


def _leer_sesion(ruta):
    st = os.stat(ruta)
    c = _cache_ses.get(ruta)
    if c and c["tam"] == st.st_size:
        return c
    if not c or st.st_size < c["tam"]:
        c = {"tam": 0, "off": 0, "tokens": 0, "ids": set(), "titulo": "", "primero": "", "cwd": "",
             "id": Path(ruta).stem, "entrada": "", "ultimo": "", "eventos": []}
    with open(ruta, "rb") as f:
        f.seek(c["off"])
        resto = b""
        for linea in f:
            if not linea.endswith(b"\n"):
                resto = linea
                break
            c["off"] += len(linea)
            if b'"usage"' not in linea and b'"type":"user"' not in linea and b'title"' not in linea \
                    and b'"cwd"' not in linea and b'"last-prompt"' not in linea:
                continue
            try:
                d = json.loads(linea)
            except ValueError:
                continue
            tipo = d.get("type")
            if not c["cwd"] and d.get("cwd"):
                c["cwd"] = d["cwd"]
            if not c["entrada"] and d.get("entrypoint"):
                c["entrada"] = d["entrypoint"]
            if tipo in ("ai-title", "custom-title", "summary"):
                t = d.get("customTitle") or d.get("aiTitle") or d.get("title") or d.get("summary")
                if t and (tipo == "custom-title" or not c.get("titulo_fijo")):
                    c["titulo"] = t
                    c["titulo_fijo"] = tipo == "custom-title"
            elif tipo == "last-prompt" and d.get("lastPrompt"):
                c["ultimo"] = " ".join(d["lastPrompt"].split())
            elif tipo == "user" and not c["primero"] and not d.get("isMeta") and not d.get("isSidechain"):
                c["primero"] = _texto_usuario((d.get("message") or {}).get("content"))
            elif tipo == "assistant":
                m = d.get("message") or {}
                u = m.get("usage")
                mid = m.get("id")
                if u and mid not in c["ids"]:
                    c["ids"].add(mid)
                    n = sum(int(u.get(k) or 0) for k in
                            ("input_tokens", "output_tokens", "cache_creation_input_tokens", "cache_read_input_tokens"))
                    c["tokens"] += n
                    try:
                        ts = datetime.fromisoformat(d["timestamp"]).timestamp()
                        c["eventos"].append((ts, n))
                    except (KeyError, ValueError):
                        pass
    c["tam"] = c["off"]
    c["mtime"] = st.st_mtime
    _cache_ses[ruta] = c
    return c


def sesiones(n=10):
    archivos = sorted(glob.glob(str(PROYECTOS / "*" / "*.jsonl")), key=os.path.getmtime, reverse=True)
    out = []
    for ruta in archivos[:60]:
        try:
            c = _leer_sesion(ruta)
        except Exception:
            continue
        if c["entrada"].startswith("sdk"):  # sessions started by `claude -p` (scripts and other tools), not yours
            continue
        titulo = c["titulo"] or c["primero"] or c["ultimo"]
        if not titulo:
            continue
        cwd = c["cwd"] or str(HOME)
        out.append({"id": c["id"], "titulo": titulo[:140], "cwd": cwd, "carpeta": os.path.basename(cwd) or "~",
                    "fecha": c["mtime"], "tokens": c["tokens"], "vscode": c["entrada"] == "claude-vscode"})
        if len(out) >= n:
            break
    return out


