def _leer_json(p, defecto):
    try:
        return json.loads(Path(p).read_text())
    except Exception:
        return defecto


def _escribir_json(p, dato):
    p = Path(p)
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(dato, ensure_ascii=False))
    tmp.replace(p)


# ---------------------------------------------------------------- clipboard
class Copiados:
    """Clipboard history. The native app calls revisar() every half second."""

    OCULTOS = {"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"}

    def __init__(self):
        self.items = _leer_json(COPIADOS, [])
        if self.items:  # backup at startup: if something empties the list, it can be restored from here
            _escribir_json(COPIADOS.with_name("copiados.respaldo.json"), self.items)
        self.lock = threading.Lock()
        self.ultimo = None
        self.ignorar_cambio = None

    def guardar(self):
        with self.lock:
            _escribir_json(COPIADOS, self.items[:MAX_COPIADOS])

    def revisar(self, pb):
        cc = pb.changeCount()
        if cc == self.ultimo:
            return False
        primera = self.ultimo is None
        self.ultimo = cc
        if primera or cc == self.ignorar_cambio:
            return False  # whatever was there at startup, or what we just copied ourselves
        tipos = set(str(t) for t in (pb.types() or []))
        if tipos & self.OCULTOS:
            return False
        item = None
        if "public.file-url" in tipos:
            from AppKit import NSURL
            urls = pb.readObjectsForClasses_options_([NSURL], None) or []
            rutas = [str(u.path()) for u in urls if u.isFileURL()]
            if rutas:
                item = {"tipo": "archivos", "rutas": rutas}
        if item is None and (tipos & {"public.png", "public.tiff"}) and "public.utf8-plain-text" not in tipos:
            datos = pb.dataForType_("public.png") or pb.dataForType_("public.tiff")
            if datos:
                png = _a_png(datos, 1600)
                if png:
                    h = hashlib.sha1(png).hexdigest()[:16]
                    IMAGENES.mkdir(exist_ok=True)
                    (IMAGENES / f"{h}.png").write_bytes(png)
                    item = {"tipo": "imagen", "imagen": f"{h}.png"}
        if item is None:
            texto = pb.stringForType_("public.utf8-plain-text")
            if texto and texto.strip():
                item = {"tipo": "texto", "texto": str(texto)[:20000]}
        if item is None:
            return False
        item["fecha"] = time.time()
        clave = _clave(item)
        with self.lock:
            self.items = [x for x in self.items if _clave(x) != clave]
            self.items.insert(0, item)
            sobran = self.items[MAX_COPIADOS:]
            self.items = self.items[:MAX_COPIADOS]
        for x in sobran:
            if x.get("tipo") == "imagen" and not any(y.get("imagen") == x["imagen"] for y in self.items):
                (IMAGENES / x["imagen"]).unlink(missing_ok=True)
        self.guardar()
        return True

    def lista(self):
        out = []
        for i, x in enumerate(self.items[:MAX_COPIADOS]):
            y = {"i": i, "tipo": x["tipo"], "fecha": x["fecha"]}
            if x["tipo"] == "texto":
                y["texto"] = x["texto"][:600]
            elif x["tipo"] == "imagen":
                y["mini"] = _miniatura(IMAGENES / x["imagen"], 120)
            else:
                y["rutas"] = x["rutas"]
                y["nombres"] = [os.path.basename(r) for r in x["rutas"]]
                y["icono"] = icono(x["rutas"][0], 32)
            out.append(y)
        return out

    def copiar(self, i, pb):
        x = self.items[i]
        pb.clearContents()
        if x["tipo"] == "texto":
            pb.setString_forType_(x["texto"], "public.utf8-plain-text")
        elif x["tipo"] == "imagen":
            from Foundation import NSData
            pb.setData_forType_(NSData.dataWithContentsOfFile_(str(IMAGENES / x["imagen"])), "public.png")
        else:
            from AppKit import NSURL
            pb.writeObjects_([NSURL.fileURLWithPath_(r) for r in x["rutas"]])
        self.ignorar_cambio = pb.changeCount()
        self.ultimo = self.ignorar_cambio
        with self.lock:  # move it to the top
            self.items.insert(0, self.items.pop(i))
            self.items[0]["fecha"] = time.time()
        self.guardar()

    def ruta(self, i):
        """Path of a copied file or image (images live as PNGs in Atajos' folder)."""
        x = self.items[i]
        if x["tipo"] == "imagen":
            return str(IMAGENES / x["imagen"])
        return "\n".join(x.get("rutas", []))

    def copiar_varios(self, indices, pb):
        """Several at once. All text: one text, separated by blank lines. With files or images: all of them as files
        (paste into Finder, Mail, Claude Code…); any text in the selection goes along as plain text."""
        xs = [self.items[i] for i in indices if 0 <= i < len(self.items)]
        if not xs:
            return False
        from AppKit import NSURL
        textos = [x["texto"] for x in xs if x["tipo"] == "texto"]
        rutas = []
        for x in xs:
            if x["tipo"] == "imagen":
                rutas.append(str(IMAGENES / x["imagen"]))
            elif x["tipo"] == "archivos":
                rutas += x["rutas"]
        pb.clearContents()
        if rutas:
            from AppKit import NSPasteboardItem
            from Foundation import NSData
            objetos = []
            for r in rutas:  # each one as a file and, if it's an image, also as the picture itself
                it = NSPasteboardItem.alloc().init()
                it.setString_forType_(NSURL.fileURLWithPath_(r).absoluteString(), "public.file-url")
                if r.lower().endswith(".png"):
                    d = NSData.dataWithContentsOfFile_(r)
                    if d:
                        it.setData_forType_(d, "public.png")
                objetos.append(it)
            if textos:
                it = NSPasteboardItem.alloc().init()
                it.setString_forType_("\n\n".join(textos), "public.utf8-plain-text")
                objetos.append(it)
            pb.writeObjects_(objetos)
        else:
            pb.setString_forType_("\n\n".join(textos), "public.utf8-plain-text")
        self.ignorar_cambio = pb.changeCount()  # don't add the combination to the history
        self.ultimo = self.ignorar_cambio
        return True

    def copiar_rutas(self, indices, pb):
        """The paths of the selected files and images, one per line."""
        texto = "\n".join(r for i in indices if 0 <= i < len(self.items) and self.items[i]["tipo"] != "texto"
                          for r in self.ruta(i).split("\n"))
        if not texto:
            return False
        pb.clearContents()
        pb.setString_forType_(texto, "public.utf8-plain-text")
        self.ignorar_cambio = pb.changeCount()
        self.ultimo = self.ignorar_cambio
        return True

    def copiar_ruta(self, i, pb):
        texto = self.ruta(i)
        if not texto:
            return False
        pb.clearContents()
        pb.setString_forType_(texto, "public.utf8-plain-text")
        self.ignorar_cambio = pb.changeCount()  # don't add the path to the history as a new item
        self.ultimo = self.ignorar_cambio
        return True

    def borrar(self, i):
        with self.lock:
            x = self.items.pop(i)
        if x.get("tipo") == "imagen":
            (IMAGENES / x["imagen"]).unlink(missing_ok=True)
        self.guardar()

    def limpiar(self):
        with self.lock:
            self.items = []
        for f in IMAGENES.glob("*.png"):
            f.unlink(missing_ok=True)
        self.guardar()


def _clave(x):
    return (x["tipo"], x.get("texto") or x.get("imagen") or tuple(x.get("rutas", [])))


# ---------------------------------------------------------------- images and icons
def _a_png(datos, lado_max):
    from AppKit import NSBitmapImageRep, NSImage
    img = NSImage.alloc().initWithData_(datos)
    if img is None:
        return None
    return _imagen_png(img, lado_max)


def _imagen_png(img, lado):
    from AppKit import NSBitmapImageRep, NSCalibratedRGBColorSpace, NSCompositingOperationCopy, NSGraphicsContext, NSMakeRect
    w, h = img.size().width, img.size().height
    if not w or not h:
        return None
    k = min(1.0, lado / max(w, h))
    W, H = max(1, int(w * k)), max(1, int(h * k))
    rep = NSBitmapImageRep.alloc().initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bytesPerRow_bitsPerPixel_(
        None, W, H, 8, 4, True, False, NSCalibratedRGBColorSpace, 0, 0)
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.setCurrentContext_(NSGraphicsContext.graphicsContextWithBitmapImageRep_(rep))
    img.drawInRect_fromRect_operation_fraction_(NSMakeRect(0, 0, W, H), NSMakeRect(0, 0, w, h), NSCompositingOperationCopy, 1.0)
    NSGraphicsContext.restoreGraphicsState()
    return bytes(rep.representationUsingType_properties_(4, {}))  # 4 = PNG


_cache_iconos = {}


IMAGEN_EXT = (".png", ".jpg", ".jpeg", ".heic", ".gif", ".webp", ".tiff")


def icono(ruta, lado=32):
    """The file's Finder icon as a data URL (at 2x for Retina screens); images get their thumbnail."""
    ext = os.path.splitext(ruta)[1].lower()
    if ext in IMAGEN_EXT and os.path.isfile(ruta) and os.path.getsize(ruta) < 40_000_000:
        clave = ("mini", ruta, os.path.getmtime(ruta))
        if clave not in _cache_iconos:
            _cache_iconos[clave] = _miniatura(ruta, lado) or ""
        if _cache_iconos[clave]:
            return _cache_iconos[clave]
    clave = ruta if (not ext or ext in (".app", ".pdf", ".png", ".jpg", ".jpeg", ".heic", ".mov", ".mp4")) else ext
    if clave in _cache_iconos:
        return _cache_iconos[clave]
    try:
        from AppKit import NSWorkspace
        img = NSWorkspace.sharedWorkspace().iconForFile_(ruta)
        png = _imagen_png(img, lado * 2)
        url = "data:image/png;base64," + base64.b64encode(png).decode()
    except Exception:
        url = ""
    if len(_cache_iconos) > 500:
        _cache_iconos.clear()
    _cache_iconos[clave] = url
    return url


def _miniatura(ruta, lado):
    try:
        from AppKit import NSImage
        img = NSImage.alloc().initWithContentsOfFile_(str(ruta))
        return "data:image/png;base64," + base64.b64encode(_imagen_png(img, lado * 2)).decode()
    except Exception:
        return ""


# ---------------------------------------------------------------- Spotify
def _osa(script, timeout=4):
    r = subprocess.run(["osascript", "-e", script], capture_output=True, text=True, timeout=timeout)
    return r.stdout.strip(), r.returncode


def spotify_abierto():
    from AppKit import NSWorkspace
    return any(a.bundleIdentifier() == "com.spotify.client" for a in NSWorkspace.sharedWorkspace().runningApplications())


def spotify():
    if not spotify_abierto():
        return {"abierto": False}
    sep = "‖"
    out, rc = _osa(f'''tell application "Spotify"
        set e to player state as string
        if e is "stopped" then return e
        set t to current track
        return e & "{sep}" & (name of t) & "{sep}" & (artist of t) & "{sep}" & (album of t) & "{sep}" & (artwork url of t) & "{sep}" & (duration of t) & "{sep}" & (player position as string) & "{sep}" & (spotify url of t)
    end tell''')
    if rc != 0:
        return {"abierto": True, "error": "Allow Atajos to control Spotify (Settings › Privacy › Automation)."}
    p = out.split(sep)
    if p[0] == "stopped" or len(p) < 8:
        return {"abierto": True, "estado": "stopped"}
    try:
        dur, pos = float(p[5]) / 1000, float(p[6].replace(",", "."))
    except ValueError:
        dur, pos = 0, 0
    return {"abierto": True, "estado": p[0], "titulo": p[1], "artista": p[2], "album": p[3],
            "portada": p[4], "duracion": dur, "posicion": pos, "url": p[7]}


def spotify_accion(accion):
    if accion == "abrir":
        subprocess.run(["open", "-b", "com.spotify.client"])
        return True
    if accion not in ("playpause", "next track", "previous track"):
        return False
    _osa(f'tell application "Spotify" to {accion}')
    return True


