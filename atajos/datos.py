def recientes(n=15):
    if time.time() - _cache_recientes["t"] < 20:
        return _cache_recientes["lista"]
    try:
        r = subprocess.run(["mdfind", "-onlyin", str(HOME), "-attr", "kMDItemLastUsedDate",
                            "kMDItemLastUsedDate >= $time.today(-7) && kMDItemContentTypeTree != public.folder"],
                           capture_output=True, text=True, timeout=8)
    except Exception:
        return _cache_recientes["lista"]
    vistos = []
    for linea in r.stdout.splitlines():
        if "   kMDItemLastUsedDate = " not in linea:
            continue
        ruta, fecha = linea.split("   kMDItemLastUsedDate = ", 1)
        ruta = ruta.strip()
        nombre = os.path.basename(ruta)
        if any(f in ruta + "/" for f in FUERA) or nombre.startswith(".") or "/." in ruta.replace(str(HOME), ""):
            continue
        if not os.path.exists(ruta):
            continue
        try:
            t = time.mktime(time.strptime(fecha.strip()[:19], "%Y-%m-%d %H:%M:%S")) - time.timezone + (3600 if time.daylight and time.localtime().tm_isdst else 0)
        except ValueError:
            continue
        vistos.append((t, ruta))
    vistos.sort(reverse=True)
    lista = []
    for t, ruta in vistos[:n]:
        carpeta = os.path.dirname(ruta).replace(str(HOME), "~")
        lista.append({"ruta": ruta, "nombre": os.path.basename(ruta), "carpeta": carpeta, "fecha": t, "icono": icono(ruta, 24)})
    _cache_recientes.update(t=time.time(), lista=lista)
    return lista


