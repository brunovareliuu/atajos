def abrir_terminal(cwd, comando):
    """New Terminal window in `cwd` running `comando` (Terminal rather than Ghostty)."""
    linea = f"cd {shlex.quote(cwd)} && {comando}"
    # ensure_ascii=False: AppleScript doesn't understand \uXXXX, so folders with accents or ñ would break.
    script = f"""tell application "Terminal"
        do script {json.dumps(linea, ensure_ascii=False)}
        activate
    end tell"""
    r = subprocess.run(["osascript", "-e", script], capture_output=True, text=True, timeout=20)
    if r.returncode != 0:
        print("Terminal failed:", r.stderr.strip())
        return False
    return True


def abrir_sesion(id_, cwd):
    """Resumes a Claude Code session in Terminal."""
    if not os.path.isdir(cwd):
        cwd = str(HOME)
    if not all(c.isalnum() or c == "-" for c in id_):
        return False
    return abrir_terminal(cwd, f"claude --resume {id_}")


def _corta(ruta):
    r = str(ruta)
    return "~" + r[len(str(HOME)):] if r.startswith(str(HOME)) else r


def carpetas_nueva_sesion():
    """Shortcuts for "New session": your home folder (root), your extra folders, Desktop and the folders of your recent sessions."""
    fijas = [("~", HOME)] + [(n, HOME / sub) for n, sub in carpetas_propias()] + [("Desktop", HOME / "Desktop")]
    out, vistas = [], set()
    for nombre, ruta in fijas:
        if ruta.is_dir():
            out.append({"nombre": nombre, "ruta": str(ruta), "corta": _corta(ruta)})
            vistas.add(str(ruta))
    try:
        for x in sesiones():
            c = x.get("cwd") or ""
            if c and c not in vistas and os.path.isdir(c):
                out.append({"nombre": os.path.basename(c) or c, "ruta": c, "corta": _corta(c)})
                vistas.add(c)
            if len(out) >= 8:
                break
    except Exception as e:  # noqa: BLE001
        print("carpetas_nueva_sesion:", e)
    return out


def resolver_carpeta(base, nombre):
    """Empty `nombre` → the base; starting with ~ or / → a full path; otherwise → a subfolder inside the base."""
    nombre = (nombre or "").strip()
    if nombre.startswith(("~", "/")):
        ruta = Path(os.path.expanduser(nombre))
    elif nombre:
        ruta = Path(os.path.expanduser(base or "~")) / nombre
    else:
        ruta = Path(os.path.expanduser(base or "~"))
    return ruta.resolve()


def nueva_sesion(base, nombre):
    ruta = resolver_carpeta(base, nombre)
    creada = False
    if not ruta.exists():
        ruta.mkdir(parents=True)
        creada = True
    if not ruta.is_dir():
        return {"ok": False, "error": "Not a folder"}
    ok = abrir_terminal(str(ruta), "claude")
    return {"ok": ok, "ruta": _corta(ruta), "creada": creada}


_tokens = {"t": 0, "h5": 0, "d7": 0, "listo": False}
_tokens_lock = threading.Lock()


def contar_tokens():
    """Tokens across all your sessions in the last 5 h and 7 days (incremental read; slow the first time)."""
    if not _tokens_lock.acquire(blocking=False):
        return _tokens
    try:
        ahora = time.time()
        h5 = d7 = 0
        for ruta in glob.glob(str(PROYECTOS / "*" / "*.jsonl")):
            try:
                if os.path.getmtime(ruta) < ahora - 7 * 86400:
                    continue
                c = _leer_sesion(ruta)
            except Exception:
                continue
            for ts, n in c["eventos"]:
                if ts >= ahora - 7 * 86400:
                    d7 += n
                    if ts >= ahora - 5 * 3600:
                        h5 += n
        _tokens.update(t=ahora, h5=h5, d7=d7, listo=True)
    finally:
        _tokens_lock.release()
    return _tokens


def tokens_locales():
    return dict(_tokens)


